/** Live crypto quotes come from Finnhub's Binance USDT pairs (USDT tracks the dollar). */
export function finnhubQuoteSymbol(ticker: string) {
  return isCryptoTicker(ticker) ? `BINANCE:${ticker.slice(2, -3)}USDT` : ticker;
}
