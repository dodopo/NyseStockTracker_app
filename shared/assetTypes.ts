export type AssetType = keyof typeof ASSET_TYPES;
export const ASSET_TYPE_IDS = Object.keys(ASSET_TYPES) as AssetType[];

export function isAssetType(value: unknown): value is AssetType {
  return typeof value === "string" && Object.hasOwn(ASSET_TYPES, value);
}

/** Tab colors offered in the UI (validated on the server). */
export const TAB_COLORS = ["#2962ff", "#089981", "#f7931a", "#ab47bc", "#f23645", "#26a69a", "#ffb74d", "#78909c"] as const;

/** Crypto assets are stored in the Massive format, priced in US dollars: X:BTCUSD. */
export const CRYPTO_TICKER_RE = /^X:[A-Z0-9]{2,15}USD$/;

export function isCryptoTicker(ticker: string) {
  return CRYPTO_TICKER_RE.test(ticker);
}

/** Assets valued by the user: I: = illiquid (dated valuations), C: = cash (price 1). */
export const MANUAL_TICKER_RE = /^[IC]:[A-Z0-9]{10}$/;
export const MANUAL_PREFIX = { illiquid: "I:", cash: "C:" } as const;
export type ManualAssetType = keyof typeof MANUAL_PREFIX;

export function isManualTicker(ticker: string) {
  return MANUAL_TICKER_RE.test(ticker);
}
export function isManualType(type: AssetType): type is ManualAssetType {
  return type === "illiquid" || type === "cash";
}

export function assetTypeOfTicker(ticker: string): AssetType {
  if (isCryptoTicker(ticker)) return "crypto";
  if (isManualTicker(ticker)) return ticker.startsWith("C:") ? "cash" : "illiquid";
  return "us_stock";
}

/** What the user sees: "X:BTCUSD" -> "BTC", "AAPL" -> "AAPL" (manual assets: see assetLabel). */
export function displaySymbol(ticker: string) {
  return isCryptoTicker(ticker) ? ticker.slice(2, -3) : ticker;
}

/** Short name of an asset on screen: the symbol, or the name of a manual asset (its identity is internal). */
export function assetLabel(asset: { ticker: string; name: string }) {
  return isManualTicker(asset.ticker) ? asset.name : displaySymbol(asset.ticker);
}

